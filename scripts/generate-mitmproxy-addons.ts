/**
 * Embed the mitmproxy addons (mitmproxy-addons/*.py) as strings in
 * src/generated/mitmproxy-addons.ts, so a bundled or compiled program (a
 * `bun build --compile` binary has no package directory) can still write them
 * out. src/__tests__/layer4.test.ts fails when the two drift apart.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const dir = join(root, "mitmproxy-addons");
const addons = readdirSync(dir)
  .filter((f) => f.endsWith(".py"))
  .sort();

const entries = addons
  .map(
    (f) =>
      `  ${JSON.stringify(f.replace(/\.py$/, ""))}: ${JSON.stringify(readFileSync(join(dir, f), "utf8"))},`
  )
  .join("\n");

writeFileSync(
  join(root, "src/generated/mitmproxy-addons.ts"),
  `// Generated by scripts/generate-mitmproxy-addons.ts from mitmproxy-addons/*.py. Do not edit.\n` +
    `export const MITMPROXY_ADDON_SOURCES = {\n${entries}\n} as const;\n`
);
console.log(`embedded ${addons.length} addon(s): ${addons.join(", ")}`);
